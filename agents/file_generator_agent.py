import json
from pathlib import Path


def generate_project_files(requirements, project_path):

    project_path = Path(project_path)

    readme_content = f"""
# {requirements.get("project_title")}

Generated by AI Meeting Agent

## Features

{chr(10).join('- ' + f for f in requirements.get("features", []))}
"""

    with open(project_path / "README.md", "w", encoding="utf-8") as f:
        f.write(readme_content)

    with open(project_path / "project_config.json", "w", encoding="utf-8") as f:
        json.dump(
            requirements,
            f,
            indent=4
        )

    return {
        "status": "files_generated"
    }